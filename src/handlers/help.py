"""Обработчик команды /help."""

from telegram import Update
from telegram.ext import ContextTypes


async def help_command(update: Update, context: ContextTypes.DEFAULT_TYPE) -> None:
    """Показать справку."""
    await update.message.reply_text(
        "🧠 **Coach Bot** — AI-психолог для предпринимателей\n\n"
        "**Команды:**\n"
        "• `/start` — Начать диалог\n"
        "• `/new` — Сбросить историю и начать заново\n"
        "• `/help` — Эта справка\n\n"
        "**Как работать:**\n"
        "Просто пиши свои мысли, вопросы, идеи — я отвечу как опытный наставник.\n\n"
        "**Что я умею:**\n"
        "• 💬 Помогать формулировать мысли для общения и переговоров\n"
        "• 🎯 Ставить цели и планировать шаги\n"
        "• 🧱 Разбирать страхи и возражения\n"
        "• 💡 Оценивать бизнес-идеи\n\n"
        "Напиши что-нибудь — и начнём! 👇"
    )
